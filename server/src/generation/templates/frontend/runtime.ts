// ── client/src/components/DataTable.tsx ────────────────────────────
export const renderDataTableTsx = (): string =>
  withTrailingNewline(
    lines(
      banner('Generic data table.'),
      `import type { ReactNode } from 'react';`,
      ``,
      `export interface Column { key: string; label: string; }`,
      ``,
      `interface Props {`,
      `  columns: Column[];`,
      `  rows: Record<string, any>[];`,
      `  renderCell: (row: Record<string, any>, col: Column) => ReactNode;`,
      `  actions?: (row: Record<string, any>) => ReactNode;`,
      `}`,
      ``,
      `export default function DataTable({ columns, rows, renderCell, actions }: Props) {`,
      `  return (`,
      `    <table className="table">`,
      `      <thead>`,
      `        <tr>`,
      `          {columns.map((c) => (`,
      `            <th key={c.key}>{c.label}</th>`,
      `          ))}`,
      `          {actions ? <th>Actions</th> : null}`,
      `        </tr>`,
      `      </thead>`,
      `      <tbody>`,
      `        {rows.map((row) => (`,
      `          <tr key={String(row.id)}>`,
      `            {columns.map((c) => (`,
      `              <td key={c.key}>{renderCell(row, c)}</td>`,
      `            ))}`,
      `            {actions ? <td>{actions(row)}</td> : null}`,
      `          </tr>`,
      `        ))}`,
      `      </tbody>`,
      `    </table>`,
      `  );`,
      `}`
    )
  );

