import { IR } from '../types';
import { lines, withTrailingNewline } from './helpers';

/**
 * Deploy-bundle renderers (Phase 5). Emitted by the Bundler stage so the
 * generated app ships deploy-ready: a Dockerfile, a Railway + Render config, a
 * LICENSE, and step-by-step self-host instructions. All deterministic (no clock
 * / random) so the golden snapshot stays stable.
 */

const dbName = (ir: IR) => `flowforge_${ir.domain}`;

// ── Dockerfile (multi-stage: build TS → slim runtime) ──────────────
export const renderDockerfile = (): string =>
  withTrailingNewline(
    lines(
      `# syntax=docker/dockerfile:1`,
      `# Build stage`,
      `FROM node:22-alpine AS build`,
      `WORKDIR /app`,
      `COPY package*.json ./`,
      `RUN npm ci`,
      `COPY . .`,
      `RUN npm run build`,
      ``,
      `# Runtime stage`,
      `FROM node:22-alpine`,
      `WORKDIR /app`,
      `ENV NODE_ENV=production`,
      `COPY package*.json ./`,
      `RUN npm ci --omit=dev`,
      `COPY --from=build /app/dist ./dist`,
      `EXPOSE 4000`,
      `CMD ["node", "dist/server.js"]`
    )
  );

export const renderDockerignore = (): string =>
  withTrailingNewline(lines(`node_modules`, `dist`, `.env`, `*.log`, `.git`));

